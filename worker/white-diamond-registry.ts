export type WhiteDiamondState = "LIVE" | "DEGRADED" | "CONFIGURATION_REQUIRED" | "SIMULATED" | "OFFLINE";
export type WhiteDiamondAgent = {
  agent_id: string;
  label: string;
  provider: string;
  kind: "manager" | "specialist" | "runtime";
  state: WhiteDiamondState;
  capabilities: string[];
  route: string;
  runtime: string;
  model: string | null;
  auth_ref: string | null;
  health_ref: string;
  quota_ref: string | null;
  priority: number;
  fallback_agent_id: string | null;
};

export type RegistryEnv = Record<string, unknown>;

function has(env: RegistryEnv, key: string) {
  return typeof env[key] === "string" && String(env[key]).trim().length > 0;
}

function configured(env: RegistryEnv, keys: string[]): WhiteDiamondState {
  return keys.every((key) => has(env, key)) ? "DEGRADED" : "CONFIGURATION_REQUIRED";
}

